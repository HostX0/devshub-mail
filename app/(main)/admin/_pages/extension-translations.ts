export const englishExtensionText: ExtensionTranslator = (text, ...values) => text.replace(/&middot;/g, '·').replace(/\{(\d+)\}/g, (_, index) => String(values[Number(index)] ?? ''));

export function translateExtensionText(arabic: boolean, text: string, ...values: Array<string | number | null | undefined>): string {
  const trimmed = text.trim();
  const translated = arabic && Object.hasOwn(EXTENSION_ARABIC, trimmed)
    ? text.slice(0, text.indexOf(trimmed)) + EXTENSION_ARABIC[trimmed] + text.slice(text.indexOf(trimmed) + trimmed.length)
    : text;
  return englishExtensionText(translated, ...values);
}

export function useExtensionI18n(): ExtensionTranslator {
  const { isArabic } = useAdminI18n();
  return useCallback((text: string, ...values: Array<string | number | null | undefined>) => translateExtensionText(isArabic, text, ...values), [isArabic]);
}


/** Errors from older servers may be plain English; never mix them into Arabic chrome. */
export function extensionError(message: unknown, fallback: string, tr: ExtensionTranslator): string {
  if (typeof message !== 'string' || !message.trim()) return tr(fallback);
  if (tr('Request failed') === 'Request failed' || /[\u0600-\u06ff]/.test(message)) return message;
  const direct = tr(message);
  if (direct !== message) return direct;
  const older = /^Version (.+) is older than the installed (.+)\.$/.exec(message);
  if (older) return tr('Version {0} is older than the installed {1}.', older[1], older[2]);
  const withdrawn = /^Version (.+?) was withdrawn by its publisher(.*)\. Pick another version, or install it anyway\.$/.exec(message);
  if (withdrawn) return tr('Version {0} was withdrawn by its publisher{1}. Pick another version, or install it anyway.', withdrawn[1], withdrawn[2]);
  return tr(fallback);
}

export function extensionDate(value: string | null, tr: ExtensionTranslator, withTime = false): string {
  if (!value) return '';
  const locale = tr('Cancel') === 'Cancel' ? 'en-US' : 'ar-IQ-u-nu-latn';
  const date = new Date(value);
  return withTime ? date.toLocaleString(locale) : date.toLocaleDateString(locale);
}

/** Package warnings retain code identifiers while translating the validation message. */
export function extensionWarning(message: string, tr: ExtensionTranslator): string {
  const patterns: Array<[RegExp, string]> = [
    [/^Ignored invalid (.+): (.+)$/, 'Ignored invalid {0}: {1}'],
    [/^Ignored permissions that no longer grant anything: (.+)$/, 'Ignored permissions that no longer grant anything: {0}'],
    [/^Left out optional permissions this Bulwark version does not offer: (.+)$/, 'Left out optional permissions this Bulwark version does not offer: {0}'],
    [/^Contains (.+) - review for security$/, 'Contains {0} - review for security'],
  ];
  for (const [pattern, key] of patterns) {
    const match = pattern.exec(message);
    if (match) return tr(key, ...match.slice(1));
  }
  return tr(message);
}
